#!/usr/bin/env node
// Generates the static language folders from one template. Run: node build.js
const fs = require('fs'), path = require('path');
const C = require('./src/content');
const VARIANTS = [
  { dir: 'en', lang: 'en', copy: 'en' },
  { dir: 'de', lang: 'de', copy: 'de' },
  { dir: 'pt-PT', lang: 'pt-PT', copy: 'pt' },
  { dir: 'pt', lang: 'pt', copy: 'pt' },
  { dir: 'nolang', lang: null, copy: 'en' },
  { dir: 'en-US', lang: 'en-US', copy: 'en' },
  { dir: 'de-DE', lang: 'de-DE', copy: 'de' },
  { dir: 'de-nolang', lang: null, copy: 'de' },
  { dir: 'en-de', lang: 'en', copy: 'de' },
  { dir: 'fr-en', lang: 'fr', copy: 'en' },
];
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
function page(v, key) {
  const c = C[v.copy], p = c[key], other = key === 'p1' ? 'page2.html' : 'index.html';
  const langAttr = v.lang ? ` lang="${v.lang}"` : '';
  return `<!DOCTYPE html>
<!-- GENERATED by build.js from src/ — do not edit by hand. Variant: ${v.dir} -->
<html${langAttr}>
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <meta name="qa-base" content="../">
  <title>${esc(p.title)}</title>
  <link rel="stylesheet" href="../assets/site.css">
  <script src="../assets/qa.js"></script>
</head>
<body data-variant="${v.dir}" data-page="${key === 'p1' ? 'index' : 'page2'}">
  <header class="site-header">
    <div class="brand-mark" translate="no">Northwind</div>
    <nav>
      <a href="./index.html">${esc(c.nav[0])}</a>
      <a href="./page2.html">${esc(c.nav[1])}</a>
      <a href="./${key === 'p1' ? 'index' : 'page2'}.html#section">${esc(c.nav[2])}</a>
    </nav>
    <div id="qa-slot-header" class="widget-slot"></div>
  </header>
  <main>
    <h1>${esc(p.h1)}</h1>
    <p class="lead">${esc(p.lead)}</p>
    <h2>${esc(p.h2a)}</h2>
    <ul>${p.list.map(x => `\n      <li>${esc(x)}</li>`).join('')}
    </ul>
    <p><button type="button" class="cta">${esc(p.button)}</button> <a href="./${other}">${esc(key === 'p1' ? c.nav[1] : c.nav[0])} →</a></p>
    <h2>${esc(p.h2b)}</h2>
${p.paras.map(x => `    <p>${esc(x)}</p>`).join('\n')}

    <h2 id="exclusions">${esc(c.exclH)}</h2>
    <p class="brand" data-qa-brand>${esc(c.brand)}</p>
    <p class="notranslate">${esc(c.excl.notranslate)}</p>
    <p translate="no">${esc(c.excl.translateNo)}</p>
    <p id="qa-exclude-target" data-qa-exclude="true">${esc(c.excl.data)}</p>
    <p><span class="sku" data-qa-exclude="sku">${esc(c.excl.sku)}</span></p>

    <h2>${esc(c.loadMore)}</h2>
    <p><button type="button" id="qa-load-more">${esc(c.loadMore)}</button></p>
    <p id="qa-auto" hidden>${esc(c.autoNote)}</p>
    <div id="qa-dyn"></div>
    <template id="qa-dyn-tpl"><p class="dyn">${esc(c.dyn).replace('{n}', '<span data-n></span>')}</p></template>

    <div class="spacer"><p>${esc(c.spacer)}</p></div>
    <section id="section">
      <h2>${esc(p.sectionH)}</h2>
      <p>${esc(p.sectionP)}</p>
    </section>
  </main>
  <footer><p>${esc(c.footer)}</p></footer>
</body>
</html>
`;
}
for (const v of VARIANTS) {
  fs.mkdirSync(path.join(__dirname, v.dir), { recursive: true });
  fs.writeFileSync(path.join(__dirname, v.dir, 'index.html'), page(v, 'p1'));
  fs.writeFileSync(path.join(__dirname, v.dir, 'page2.html'), page(v, 'p2'));
  console.log('built', v.dir);
}
